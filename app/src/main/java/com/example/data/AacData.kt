    People    ("people",    "👥"),
    Places    ("places",    "📍"),
    Medical   ("medical",   "🏥"),
    Time      ("time",      "🕒"),
    Questions ("questions", "❓"),
    Emotions  ("emotions",  "💭"),
    Emergency ("emergency", "🚨")
}

/** AAC 金額單位（自訂金額時可選） */
enum class Currency(val code: String, val symbol: String, val displayName: String) {
    NTD("NTD", "NT$", "新台幣"),
    USD("USD", "US$", "美元"),
    JPY("JPY", "¥",   "日圓"),
    KRW("KRW", "₩",   "韓圜"),
    CNY("CNY", "¥",   "人民幣"),
    EUR("EUR", "€",   "歐元")
}

/** 建立自訂金額 [AacItem]（金額類別下的「自訂」入口會用） */
fun customAmountItem(amount: String, currency: Currency): AacItem = AacItem(
    id = "custom_${currency.code}_$amount",
    label = "${currency.symbol}$amount",
    emoji = "💰",
    category = AacCategory.Money
)

