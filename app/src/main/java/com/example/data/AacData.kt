/**
 * AAC 溝通板：類別與條目資料模型（檳榔攤老闆情境預設庫）。
 *
 * UX 設計：以情境分類收納大量圖卡；畫面端用下拉選單 + 搜尋縮小選項，
 * 讓觸控、眼動、識字卡三種操作模式都能快速找到要表達的詞。
