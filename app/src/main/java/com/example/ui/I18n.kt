 * 為何不全用 strings.xml：很多字串在非 composable 範圍（lambda/coroutine 的狀態指派、ViewModel
 * 訊息）產生，`stringResource()` 只能在 composable 內呼叫；`I18n.tr()` 是純函式、哪裡都能用。
